unsigned long long Fnv1a64(const void* data, size_t size) {
    const unsigned char* bytes = static_cast<const unsigned char*>(data);
    unsigned long long hash = 0xCBF29CE484222325ull;
    for (size_t i = 0; i < size; ++i) {
        hash ^= bytes[i];
        hash *= 0x100000001B3ull;
    }
    return hash;
}

pD3DCompile RealCompiler() {
    static const pD3DCompile compile = []() -> pD3DCompile {
        HMODULE dll = LoadLibraryExW(L"d3dcompiler_47.dll", nullptr, LOAD_LIBRARY_SEARCH_SYSTEM32);
        return dll ? reinterpret_cast<pD3DCompile>(GetProcAddress(dll, "D3DCompile")) : nullptr;
    }();
    return compile;
}


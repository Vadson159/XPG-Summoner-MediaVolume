// --- Precompiled shaders for Dear ImGui's DX11 backend ---------------------
// imgui_impl_dx11.cpp compiles its two tiny shaders at runtime with
// D3DCompile(). That maps the 4.5 MB d3dcompiler_47.dll into this always-
// resident process for its whole lifetime, and runs the HLSL compiler on the
// render thread at startup and again on every font reload and device rebuild -
// which, since the device is released while idle, means every time the OSD
// first appears after a quiet spell. ImGui's own comment calls
// precompiling them "the preferred solution", but the backend takes no
// bytecode, only source.
//
// So D3DCompile is defined here. The backend calls it without dllimport, which
// means the linker resolves the call to this definition instead of pulling the
// import from d3dcompiler.lib, and the DLL is never loaded at all. A request
// for exactly the source the arrays below were generated from is answered from
// them; anything else - a different ImGui version, or any future caller - falls
// through to the real compiler, loaded on first use. A stale table therefore
// costs the DLL load it was meant to avoid, never a wrong shader.
//
// Regenerating after an ImGui upgrade: take the two HLSL literals from
// backends/imgui_impl_dx11.cpp exactly as the C++ compiler sees them (the
// backslash-newline continuations spliced out, leading spaces kept), and
// compile each with "fxc /T vs_4_0 /E main" resp. "fxc /T ps_4_0 /E main" -
// fxc's defaults are the flags the backend passes (0, 0). Record the source's
// byte length and FNV-1a 64-bit hash next to the bytecode.

